#!/usr/bin/env python3
"""Generate native theme resources from the shared, reviewed design tokens."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TOKENS = json.loads((ROOT / 'design-system/tokens.json').read_text())


def kebab(name):
    return re.sub(r'([A-Z])', lambda m: '-' + m[1].lower(), name)


def outputs():
    files = {}
    colors = TOKENS['colors']
    css = '/* Generated by scripts/generate-design-system.py. Do not edit. */\n'
    for mode, selector in [('light', ':root'), ('dark', 'html[data-theme=dark]')]:
        css += selector + '{color-scheme:' + mode + ';'
        css += ''.join(f'--tek-{kebab(key)}:{value};' for key, value in colors[mode].items())
        if mode == 'light':
            for group in ('spacing', 'radius', 'layout'):
                css += ''.join(f'--tek-{group}-{kebab(key)}:{value}px;' for key, value in TOKENS[group].items())
        css += '}\n'
    files['clients/web/design-tokens.css'] = css

    for platform, directory in [('ios', 'TEKtalk'), ('macos', 'TEKtalkMac')]:
        base = f'clients/{platform}/{directory}'
        swift = '// Generated by scripts/generate-design-system.py. Do not edit.\nimport SwiftUI\n\nenum TekDesign {\n'
        swift += ''.join(f'    static let {name} = Color("Tek{name[0].upper() + name[1:]}")\n' for name in colors['light'])
        for group in ('spacing', 'radius', 'layout'):
            swift += f'    enum {group.capitalize()} {{\n'
            swift += ''.join(f'        static let {key}: CGFloat = {value}\n' for key, value in TOKENS[group].items())
            swift += '    }\n'
        swift += '''}

struct TekPrimaryButtonStyle: ButtonStyle {
    @Environment(\\.isEnabled) private var isEnabled
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .font(.body.weight(.semibold))
            .foregroundStyle(TekDesign.onPrimary)
            .padding(.horizontal, TekDesign.Spacing.lg)
            .frame(minHeight: TekDesign.Layout.touchTarget)
            .background(TekDesign.primary, in: RoundedRectangle(cornerRadius: TekDesign.Radius.control))
            .opacity(isEnabled ? (configuration.isPressed ? 0.8 : 1) : 0.5)
    }
}
'''
        files[f'{base}/Presentation/DesignSystem.swift'] = swift
        asset = f'{base}/DesignSystem.xcassets'
        files[f'{asset}/Contents.json'] = json.dumps({'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n'
        for name in colors['light']:
            entries = []
            for mode in ('light', 'dark'):
                value = colors[mode][name].lstrip('#')
                entry = {'idiom': 'universal', 'color': {'color-space': 'srgb', 'components': dict(zip(('red', 'green', 'blue'), ('0x' + value[i:i+2] for i in (0, 2, 4))), alpha='1.000')}}
                if mode == 'dark':
                    entry['appearances'] = [{'appearance': 'luminosity', 'value': 'dark'}]
                entries.append(entry)
            files[f'{asset}/Tek{name[0].upper() + name[1:]}.colorset/Contents.json'] = json.dumps({'colors': entries, 'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n'

    kotlin = '// Generated by scripts/generate-design-system.py. Do not edit.\npackage vn.tektalk.presentation\n\nimport androidx.compose.material3.*\nimport androidx.compose.ui.graphics.Color\n\nobject TekDesign {\n'
    mapping = {'primary':'primary','onPrimary':'onPrimary','primaryContainer':'primaryContainer','onPrimaryContainer':'onPrimaryContainer','background':'background','onBackground':'text','surface':'surface','onSurface':'text','surfaceVariant':'surfaceVariant','onSurfaceVariant':'muted','outline':'outline','error':'error','onError':'onError','secondary':'primary','onSecondary':'onPrimary','secondaryContainer':'primaryContainer','onSecondaryContainer':'onPrimaryContainer'}
    for mode in ('light','dark'):
        kotlin += f'    private val {mode} = {mode}ColorScheme(\n'
        kotlin += ',\n'.join(f'        {target} = Color(0xFF{colors[mode][source][1:]})' for target, source in mapping.items()) + '\n    )\n'
    kotlin += '    const val wideBreakpoint = ' + str(TOKENS['layout']['wideBreakpoint']) + '\n'
    kotlin += '    const val bubbleRadius = ' + str(TOKENS['radius']['bubble']) + '\n'
    kotlin += '    fun colors(isDark: Boolean) = if (isDark) dark else light\n}\n'
    files['clients/android/app/src/main/java/vn/tektalk/presentation/DesignSystem.kt'] = kotlin
    for tab in TOKENS['navigation']:
        files[f"clients/android/app/src/main/res/drawable/tek_{tab['id']}.xml"] = f'''<!-- Generated by scripts/generate-design-system.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:fillColor="#FF000000" android:pathData="{tab['path']}" />
</vector>
'''

    xaml = '<!-- Generated by scripts/generate-design-system.py. Do not edit. -->\n<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n  <ResourceDictionary.ThemeDictionaries>\n'
    for mode in ('light', 'dark'):
        xaml += f'    <ResourceDictionary x:Key="{mode.capitalize()}">\n'
        for name, value in colors[mode].items():
            key = name[0].upper() + name[1:]
            xaml += f'      <SolidColorBrush x:Key="Tek{key}Brush" Color="{value}" />\n'
        # Native WinUI controls retain platform behavior while sharing tokens.
        for key, source in {'TextFillColorPrimaryBrush':'text', 'TextFillColorSecondaryBrush':'muted', 'ApplicationPageBackgroundThemeBrush':'surface', 'AccentFillColorDefaultBrush':'primary', 'TextOnAccentFillColorPrimaryBrush':'onPrimary'}.items():
            xaml += f'      <SolidColorBrush x:Key="{key}" Color="{colors[mode][source]}" />\n'
        xaml += f'      <Color x:Key="SystemAccentColor">{colors[mode]["primary"]}</Color>\n'
        xaml += '    </ResourceDictionary>\n'
    xaml += '    <ResourceDictionary x:Key="HighContrast">\n'
    hc = {'primary':'Highlight', 'onPrimary':'HighlightText', 'primaryContainer':'Highlight', 'onPrimaryContainer':'HighlightText', 'background':'Window', 'surface':'Window', 'surfaceVariant':'Window', 'text':'WindowText', 'muted':'WindowText', 'outline':'WindowText', 'error':'WindowText', 'onError':'Window', 'success':'WindowText'}
    for name, source in hc.items():
        key = name[0].upper() + name[1:]
        xaml += f'      <SolidColorBrush x:Key="Tek{key}Brush" Color="{{ThemeResource SystemColor{source}Color}}" />\n'
    xaml += '    </ResourceDictionary>\n'
    xaml += '  </ResourceDictionary.ThemeDictionaries>\n</ResourceDictionary>\n'
    files['clients/windows/TEKtalk.Windows/DesignMetrics.h'] = '#pragma once\n// Generated by scripts/generate-design-system.py.\nnamespace tektalk::design { inline constexpr double SidebarWidth = ' + str(TOKENS['layout']['sidebar']) + '; inline constexpr double TouchTarget = ' + str(TOKENS['layout']['touchTarget']) + '; }\n'
    files['clients/windows/TEKtalk.Windows/DesignSystem.xaml'] = xaml
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Fail if committed resources differ from the source tokens')
    args = parser.parse_args()
    stale = []
    for relative, content in outputs().items():
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    if stale:
        print('Regenerate Design System resources:\n' + '\n'.join(stale), file=sys.stderr)
        return 1
    print('Design System resources are consistent.' if args.check else 'Design System resources generated.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
